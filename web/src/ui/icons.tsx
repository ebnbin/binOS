import { memo } from 'react'
import type { ComponentType, CSSProperties, HTMLAttributes } from 'react'

export type IconProps = Omit<HTMLAttributes<HTMLSpanElement>, 'children'> & {
  size?: number
  filled?: boolean
  strokeWidth?: number
  fill?: string
}
export type MaterialIcon = ComponentType<IconProps>

function symbol(name: string): MaterialIcon {
  return function MaterialSymbol({ size = 24, filled = false, className, style, strokeWidth: _strokeWidth, fill, ...props }: IconProps) {
    return (
      <span
        aria-hidden="true"
        className={`material-symbols-rounded ${className ?? ''}`}
        data-filled={filled || fill === 'currentColor' || undefined}
        style={{ fontSize: 'var(--md-icon-size, var(--symbol-size))', '--symbol-size': `${size}px`, ...style } as CSSProperties}
        {...props}
      >
        {name}
      </span>
    )
  }
}

