// 不传 size 是独立图标的 20；控件里用 T 恤尺码 XS 14、S 16、M 18、L 20、XL 22（desktop），触屏上按 mobile 尺度放大
export type IconSize = 'XS' | 'S' | 'M' | 'L' | 'XL'
export type IconProps = { size?: IconSize; className?: string; style?: CSSProperties; label?: string }
export type Icon = ComponentType<IconProps>

type SpectrumGlyph = ComponentType<{ UNSAFE_className?: string; UNSAFE_style?: CSSProperties; 'aria-label'?: string; 'data-size'?: IconSize }>

// 工厂只包装官方图形，不在这个文件里定义组件，图标的导出都是组件
function spectrum(Glyph: SpectrumGlyph): Icon {
  return ({ size, className, style, label }: IconProps) =>
    createElement(Glyph, { UNSAFE_className: `${styles.icon} ${className ?? ''}`, UNSAFE_style: style, 'aria-label': label, 'data-size': size })
}

// Spectrum 2 的 workflow 图标里没有的图形用 lucide 补，线宽换算成和 Spectrum 一致的 1.5/20
function outline(Glyph: LucideIcon): Icon {
  return ({ size, className, style, label }: IconProps) =>
    createElement(Glyph, {
      className: `${styles.icon} ${className ?? ''}`,
      style,
      'data-size': size,
      strokeWidth: 1.8,
      'aria-label': label,
      'aria-hidden': label ? undefined : true,
    } as LucideProps)
}

